import { Router } from 'express';
import { getWorkItems, getWorkItemById, createWorkItem, updateWorkItem, claimWorkItem, assignWorkItem, transitionWorkItem, getActivities, addComment, getComments, } from '../controllers/workItemController.js';
import { authenticate } from '../middleware/auth.js';
import { handleIdempotency } from '../middleware/idempotency.js';
import { validateBody, validateQuery } from '../middleware/validate.js';
import { createWorkItemSchema, updateWorkItemSchema, assignWorkItemSchema, claimWorkItemSchema, transitionWorkItemSchema, commentWorkItemSchema, queryWorkItemSchema, } from '../schemas/workItemSchemas.js';
const router = Router();
router.use(authenticate);
router.get('/', validateQuery(queryWorkItemSchema), getWorkItems);
router.post('/', handleIdempotency, validateBody(createWorkItemSchema), createWorkItem);
router.get('/:id', getWorkItemById);
router.patch('/:id', validateBody(updateWorkItemSchema), updateWorkItem);
router.post('/:id/claim', validateBody(claimWorkItemSchema), claimWorkItem);
router.post('/:id/assign', validateBody(assignWorkItemSchema), assignWorkItem);
router.post('/:id/transition', validateBody(transitionWorkItemSchema), transitionWorkItem);
router.get('/:id/activities', getActivities);
router.get('/:id/comments', getComments);
router.post('/:id/comments', validateBody(commentWorkItemSchema), addComment);
export default router;
